"""Rasterize an SVG into an LVGL 9 RGB565A8 image (a .c file with an lv_image_dsc_t).

uv run --with cairosvg --with pillow src/app/images/svg2c.py <in.svg> <size> <name> [<height>]
writes src/app/images/<name>.c next to this script.
"""
import io
import sys
from pathlib import Path

import cairosvg
from PIL import Image

src, size, name = sys.argv[1], int(sys.argv[2]), sys.argv[3]
height = int(sys.argv[4]) if len(sys.argv) > 4 else size
png = cairosvg.svg2png(url=src, output_width=size, output_height=height)
img = Image.open(io.BytesIO(png)).convert("RGBA")

rgb, alpha = bytearray(), bytearray()
px = img.tobytes()
for i in range(0, len(px), 4):
    r, g, b, a = px[i:i + 4]
    v = ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
    rgb += bytes((v & 0xFF, v >> 8))  # little-endian RGB565
    alpha.append(a)
data = rgb + alpha  # RGB565A8: the colour plane, then the alpha plane

rows = "\n".join("    " + ", ".join(f"0x{x:02x}" for x in data[i:i + 16]) + ","
                 for i in range(0, len(data), 16))
out = Path(__file__).with_name(f"{name}.c")
out.write_text(f"""// Generated by svg2c.py from {Path(src).name} at {size}x{height}. Do not edit.
#include "lvgl.h"

static const uint8_t {name}_map[] = {{
{rows}
}};

const lv_image_dsc_t {name} = {{
    .header = {{
        .magic = LV_IMAGE_HEADER_MAGIC,
        .cf = LV_COLOR_FORMAT_RGB565A8,
        .flags = 0,
        .w = {size},
        .h = {height},
        .stride = {size * 2},
    }},
    .data_size = sizeof({name}_map),
    .data = {name}_map,
}};
""")
print(f"wrote {out} ({len(data)} bytes)")
